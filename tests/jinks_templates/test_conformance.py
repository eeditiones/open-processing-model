def test_nested_for(env):
    template = (
        '<div>\n  <ul>\n    [% for $person in $people?* %]\n      <li>\n'
        '        <h3>[[$person?name]], [[$person?city]]</h3>\n'
        '        [% if not($person?customer) %]\n        <p>Not a customer yet.</p>\n'
        '        [% endif %]\n        [% if count($person?phone?*) > 0 %]\n        <ul>\n'
        '        [% for $number in $person?phone?* %]\n          <li>[[ $number ]]</li>\n'
        '        [% endfor %]\n        </ul>\n        [% endif %]\n      </li>\n'
        '    [% endfor %]\n  </ul>\n</div>'
    )
    people = [
        {'name': 'Rudi Rüssel', 'city': 'Düsseldorf', 'customer': True,
         'phone': ['+4978767464', '+4915152343']},
        {'name': 'Anna Szczurek', 'city': 'Nowy Sącz', 'customer': False, 'phone': ['+48676465']},
        {'name': 'Gabi Gans', 'city': 'Frankfurt', 'customer': True},
    ]
    result = env.from_string(template, 'test.html').render({'people': people})
    assert html_equal(result, (
        '<div><ul><li><h3>Rudi Rüssel, Düsseldorf</h3><ul><li>+4978767464</li><li>+4915152343</li>'
        '</ul></li><li><h3>Anna Szczurek, Nowy Sącz</h3><p>Not a customer yet.</p><ul>'
        '<li>+48676465</li></ul></li><li><h3>Gabi Gans, Frankfurt</h3></li></ul></div>'
    )), result


def test_text_mode_conditional_attributes(env):
    template = (
        '<package>\n  [% for $dep in $dependencies?* %]\n'
        '    <dependency package="[[$dep?package]]" semver="![[$dep?semver]]" '
        'semver-min="![[$dep?semver-min]]" semver-max="![[$dep?semver-max]]"/>\n'
        '  [% endfor %]\n</package>'
    )
    params = {'dependencies': [
        {'package': 'http://example.org/a', 'semver': '1'},
        {'package': 'http://example.org/b', 'semver-min': '6.1', 'semver-max': '6'},
    ]}
    result = env.from_string(template, 'expath-pkg.xml.tpl').render(
        {**params, 'templating': {'mode': 'text'}})
    assert blank_lines(result) == (
        '<package>\n\n    <dependency package="http://example.org/a" semver="1"/>\n\n'
        '    <dependency package="http://example.org/b" semver-min="6.1" semver-max="6"/>\n\n'
        '</package>'
    )


def test_css(env):
    template = (
        '[% if $logo %]\n.logo {\n    background-image: url("[[ $logo ]]");\n}\n[% endif %]\n\n'
        'body {\n  --pb-base-font-family: [[ $font ]];\n  --pb-content-font-family: [[ $contentFont ]];\n}'
    )
    result = env.from_string(template, 'style.css').render(
        {'logo': '../images/tei-publisher-logo-color.svg', 'font': 'Helvetica', 'contentFont': 'Times'})
    assert result == (
        '\n.logo {\n    background-image: url("../images/tei-publisher-logo-color.svg");\n}\n\n\n'
        'body {\n  --pb-base-font-family: Helvetica;\n  --pb-content-font-family: Times;\n}'
    )


def test_import_is_reported(env):
    template = (
        '[% import "https://tei-publisher.com/jinks/xquery/demo" as "demo" at "modules/demo.xql" %]\n'
        '<section>[[demo:sysinfo($title)]]</section>'
    )
    with pytest.raises(TemplateSyntaxError, match='import'):
        env.from_string(template, 'test.html')


