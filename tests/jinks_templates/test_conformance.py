def test_minimal_template(env):
    assert env.from_string('<p>Hello World</p>', 'test.html').render() == '<p>Hello World</p>'


def test_malformed_syntax(env):
    with pytest.raises(TemplateSyntaxError, match='Missing endif'):
        env.from_string('<div>[% if $foo %]bar', 'test.html')


def test_invalid_mode_falls_back(env):
    tpl = env.from_string('<p>[[ $x ]]</p>', 'test.html')
    assert tpl.render({'x': '<b>', 'templating': {'mode': 'foobar'}}) == '<p>&lt;b&gt;</p>'


# api.security.cy.js


def test_script_in_params_is_escaped(env):
    result = env.from_string('<div>[[ $userInput ]]</div>', 'test.html').render(
        {'userInput': '<script>alert("xss")</script>'})
    assert '<script>' not in result
    assert result == '<div>&lt;script&gt;alert(&quot;xss&quot;)&lt;/script&gt;</div>'


def test_path_traversal_in_include(env):
    with pytest.raises(TemplateNotFound):
        env.from_string('[% include "../../../../etc/passwd" %]', 'test.html')
